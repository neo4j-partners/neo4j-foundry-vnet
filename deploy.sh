#!/usr/bin/env bash
# Deploy the network-secured Foundry + Neo4j MCP POC with azd.
# Ported from neo4j-agent-integrations/microsoft-foundry/infra/deploy.sh,
# simplified: seeds the azd env from ./.env (if present), runs `azd up`, and
# writes a shared .env.deployed with everything the agent scripts need.
set -euo pipefail

cd "$(dirname "$0")"

command -v azd >/dev/null || {
  echo "Missing azd. Install: https://learn.microsoft.com/azure/developer/azure-developer-cli/install-azd"
  exit 1
}

if ! az account show >/dev/null 2>&1 && ! azd auth login --check-status >/dev/null 2>&1; then
  echo "Not signed in. Run: az login (and 'azd auth login' if azd uses standalone auth)" >&2
  exit 1
fi

# Default azd env so a fresh clone doesn't prompt. Resource names get this as
# their suffix (rg-fdy-neo4j-vnet-poc, ...).
if [ ! -d .azure ] || [ -z "$(ls -A .azure 2>/dev/null)" ]; then
  azd env new vnet-poc >/dev/null
fi

# Forward local .env overrides into the azd environment.
if [ -f ".env" ]; then
  while IFS='=' read -r key value; do
    key="$(echo "$key" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
    value="$(echo "${value:-}" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
    if [ -z "$key" ] || [[ "$key" == \#* ]] || [ -z "$value" ]; then
      continue
    fi
    azd env set "$key" "$value" >/dev/null
  done < ".env"
fi

azd_get() {
  local out
  if out="$(azd env get-value "$1" 2>/dev/null)" && [[ "$out" != ERROR:* ]]; then
    printf '%s' "$out"
  fi
}

# Sweden Central: supports Foundry standard agents with VNet injection and the
# default gpt-5-mini model.
if [ -z "$(azd_get AZURE_LOCATION)" ]; then
  azd env set AZURE_LOCATION swedencentral >/dev/null
fi

# Neo4j password: generate a strong one on first deploy if not already set.
# Stored only in the azd env (gitignored .azure/), never committed. Neo4j
# rejects weak/short passwords, so use a 24+ char urlsafe token.
if [ -z "$(azd_get NEO4J_PASSWORD)" ]; then
  gen_pw="$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 28)"
  azd env set NEO4J_PASSWORD "$gen_pw" >/dev/null
  echo "Generated a Neo4j password and stored it in the azd env (NEO4J_PASSWORD)."
fi

# The Foundry User role assignment needs the caller's object ID; in az-cli auth
# mode azd doesn't stamp it automatically.
if [ -z "$(azd_get AZURE_PRINCIPAL_ID)" ] && command -v az >/dev/null; then
  pid="$(az ad signed-in-user show --query id -o tsv 2>/dev/null || true)"
  [ -n "$pid" ] && azd env set AZURE_PRINCIPAL_ID "$pid" >/dev/null
fi

if [ -z "$(azd_get AZURE_TENANT_ID)" ] && command -v az >/dev/null; then
  tid="$(az account show --query tenantId -o tsv 2>/dev/null || true)"
  [ -n "$tid" ] && azd env set AZURE_TENANT_ID "$tid" >/dev/null
fi

azd_up_status=0
azd up "$@" || azd_up_status=$?

# Write the shared env file for the agent scripts.
endpoint="$(azd_get mcpEndpoint)"
cat > .env.deployed <<EOF
# Auto-generated by deploy.sh — values from the last azd up.
# Private, in-VNet Neo4j (bolt://<private-ip>:7687) unless an external
# NEO4J_URI override was supplied.
NEO4J_URI=$(azd_get neo4jUri)
NEO4J_DATABASE=$(azd_get NEO4J_DATABASE)
NEO4J_USERNAME=$(azd_get NEO4J_USERNAME)
NEO4J_PASSWORD=$(azd_get NEO4J_PASSWORD)
NEO4J_PRIVATE_IP=$(azd_get neo4jPrivateIp)
NEO4J_CONTAINER_GROUP=$(azd_get neo4jContainerGroupName)

# Private MCP endpoint — resolvable ONLY inside the VNet (and by the Foundry
# agent data proxy). Curl from your laptop is expected to fail.
NEO4J_MCP_ENDPOINT=${endpoint}
MCP_FQDN=$(azd_get mcpFqdn)

AZURE_SUBSCRIPTION_ID=$(azd_get AZURE_SUBSCRIPTION_ID)
AZURE_TENANT_ID=$(azd_get AZURE_TENANT_ID)
FOUNDRY_RESOURCE_GROUP=$(azd_get foundryResourceGroup)
FOUNDRY_ACCOUNT_NAME=$(azd_get foundryAccountName)
FOUNDRY_PROJECT_ID=$(azd_get foundryProjectId)
FOUNDRY_PROJECT_NAME=$(azd_get foundryProjectName)
FOUNDRY_PROJECT_ENDPOINT=$(azd_get foundryProjectEndpoint)
FOUNDRY_MODEL_DEPLOYMENT_NAME=$(azd_get foundryModelDeploymentName)
EMBEDDING_DEPLOYMENT_NAME=$(azd_get foundryEmbeddingDeploymentName)
NEO4J_MCP_CONNECTION_NAME=$(azd_get mcpConnectionName)
FOUNDRY_PUBLIC_NETWORK_ACCESS=$(azd_get foundryPublicNetworkAccessOut)
EOF

if [ "$azd_up_status" -eq 0 ]; then
  cat <<EOF

Network-secured deployment is ready.

Private MCP endpoint (VNet-only): ${endpoint}
Foundry project endpoint:         $(azd_get foundryProjectEndpoint)

Next steps:
  ./load-data.sh             # loads the synthetic turbine graph into the private Neo4j
  ./test-private.sh          # proves the MCP endpoint is NOT publicly reachable
  uv run agent/create_and_test_agent.py   # E2E: agent -> data proxy -> VNet -> MCP -> Neo4j

EOF
else
  echo "azd up exited with status ${azd_up_status} — check the log above." >&2
  exit "$azd_up_status"
fi
