#!/usr/bin/env -S uv run --quiet
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Generate a neutral, fully synthetic wind-turbine fleet "digital twin" graph.

Emits a single self-contained `seed.cypher` (schema constraints + batched
`UNWIND` inserts, no external CSVs) that loads into Neo4j with cypher-shell.

Everything here is invented — fictional operator, sites, turbine models,
serial numbers, and simulated sensor/maintenance data. There are NO real
companies, products, people, or customer references. The graph shape
(Asset -> System -> Component -> Sensor -> Reading, plus Site and
MaintenanceEvent) is a generic industrial digital-twin pattern; swap in a
real schema later without touching the infrastructure.

The generator uses a fixed seed so repeated runs produce identical output.
"""

import random
from pathlib import Path

SEED = 42
FLEET_SIZE = 24  # turbines
DAYS = 30  # days of hourly readings
READING_EVERY_HOURS = 3  # sample every N hours to keep the seed file modest
MAINT_EVENTS = 180

# --- Fictional reference data ------------------------------------------------
OPERATOR = "Aeolus Renewables"
MODELS = [
    ("Zephyr-110", 3.4),  # (model, rated_MW)
    ("Zephyr-150", 5.2),
    ("Gale-220", 8.0),
]
SITES = [
    ("North Ridge", "GB", 55.9, -3.9),
    ("Kattegat Shoal", "DK", 56.6, 11.3),
    ("Meseta Alta", "ES", 41.2, -4.1),
    ("Windward Flats", "US", 41.6, -101.2),
]
SYSTEMS = ["Rotor", "Drivetrain", "Generator", "YawSystem"]
COMPONENTS = {
    "Rotor": ["BladeA", "BladeB", "BladeC", "PitchBearing"],
    "Drivetrain": ["Gearbox", "MainBearing", "Coupling"],
    "Generator": ["Stator", "Rotor Winding", "SlipRing"],
    "YawSystem": ["YawMotor", "YawBearing"],
}
# sensor type -> (unit, base value, noise amplitude)
SENSORS = {
    "GearboxTemp": ("C", 62.0, 6.0),
    "Vibration": ("mm/s", 2.4, 1.1),
    "RotorRPM": ("rpm", 14.5, 2.0),
    "PowerOutput": ("kW", 2600.0, 900.0),
    "WindSpeed": ("m/s", 8.5, 3.5),
}
FAULTS = [
    ("Gearbox oil over-temperature", "Drivetrain", "high"),
    ("Blade pitch actuator drift", "Rotor", "medium"),
    ("Generator bearing vibration", "Generator", "high"),
    ("Yaw misalignment", "YawSystem", "low"),
    ("Converter IGBT warning", "Generator", "medium"),
]
ACTIONS = [
    "Replaced lubricant and filter",
    "Recalibrated pitch controller",
    "Scheduled bearing replacement",
    "Adjusted yaw offset",
    "Firmware update applied",
]

START = "2025-05-01T00:00:00"


def main() -> None:
    rnd = random.Random(SEED)
    lines: list[str] = []
    w = lines.append

    w("// Synthetic wind-turbine fleet digital twin — generated by data/generate.py.")
    w(
        "// Fully fictional. Safe to load into any Neo4j. Wipes the target database first."
    )
    w("MATCH (n) DETACH DELETE n;")
    for label, key in [
        ("Turbine", "id"),
        ("System", "id"),
        ("Component", "id"),
        ("Sensor", "id"),
        ("Reading", "id"),
        ("Site", "id"),
        ("MaintenanceEvent", "id"),
    ]:
        w(
            f"CREATE CONSTRAINT {label.lower()}_id IF NOT EXISTS "
            f"FOR (n:{label}) REQUIRE n.{key} IS UNIQUE;"
        )

    # --- Sites ---
    sites = []
    for i, (name, country, lat, lon) in enumerate(SITES):
        sid = f"SITE-{i + 1:02d}"
        sites.append(sid)
        w(
            f"CREATE (:Site {{id:'{sid}', name:'{name}', country:'{country}', "
            f"latitude:{lat}, longitude:{lon}}});"
        )

    # --- Turbines + systems + components + sensors ---
    sensor_ids: list[tuple[str, str, float, float]] = []  # (id, type, base, noise)
    for t in range(1, FLEET_SIZE + 1):
        tid = f"WTG-{t:04d}"
        model, rated = rnd.choice(MODELS)
        site = rnd.choice(sites)
        commissioned = 2018 + rnd.randint(0, 6)
        w(
            f"CREATE (:Turbine {{id:'{tid}', serial:'{tid}', model:'{model}', "
            f"operator:'{OPERATOR}', rated_power_mw:{rated}, "
            f"commissioned_year:{commissioned}}});"
        )
        w(
            f"MATCH (t:Turbine {{id:'{tid}'}}), (s:Site {{id:'{site}'}}) "
            f"CREATE (t)-[:LOCATED_AT]->(s);"
        )
        for sysname in SYSTEMS:
            sysid = f"{tid}-{sysname}"
            w(
                f"MATCH (t:Turbine {{id:'{tid}'}}) "
                f"CREATE (t)-[:HAS_SYSTEM]->(:System {{id:'{sysid}', type:'{sysname}'}});"
            )
            for comp in COMPONENTS[sysname]:
                compid = f"{sysid}-{comp}".replace(" ", "")
                w(
                    f"MATCH (sy:System {{id:'{sysid}'}}) "
                    f"CREATE (sy)-[:HAS_COMPONENT]->(:Component "
                    f"{{id:'{compid}', name:'{comp}'}});"
                )
            # sensors hang off systems
            for stype, (unit, base, noise) in SENSORS.items():
                if _sensor_on_system(stype, sysname):
                    senid = f"{sysid}-{stype}"
                    sensor_ids.append((senid, stype, base, noise))
                    w(
                        f"MATCH (sy:System {{id:'{sysid}'}}) "
                        f"CREATE (sy)-[:HAS_SENSOR]->(:Sensor "
                        f"{{id:'{senid}', type:'{stype}', unit:'{unit}'}});"
                    )

    # --- Readings (batched UNWIND) ---
    hours = list(range(0, DAYS * 24, READING_EVERY_HOURS))
    reading_rows: list[str] = []
    rc = 0
    for senid, stype, base, noise in sensor_ids:
        drift = rnd.uniform(0, noise * 0.4)  # mild degradation trend per sensor
        for h in hours:
            ts = _ts(h)
            val = round(
                base + rnd.uniform(-noise, noise) + drift * (h / (DAYS * 24)), 2
            )
            rid = f"R-{rc:07d}"
            rc += 1
            reading_rows.append(
                f"{{id:'{rid}', sid:'{senid}', ts:'{ts}', value:{val}}}"
            )
    _emit_batches(
        w,
        reading_rows,
        500,
        "UNWIND $rows AS r MATCH (se:Sensor {id:r.sid}) "
        "CREATE (se)-[:GENERATES]->(:Reading "
        "{id:r.id, timestamp:datetime(r.ts), value:r.value})",
    )

    # --- Maintenance events ---
    comp_pool = [  # rebuild deterministic component id pool
        f"WTG-{t:04d}-{sysname}-{comp}".replace(" ", "")
        for t in range(1, FLEET_SIZE + 1)
        for sysname in SYSTEMS
        for comp in COMPONENTS[sysname]
    ]
    maint_rows: list[str] = []
    for m in range(MAINT_EVENTS):
        fault, sysname, severity = rnd.choice(FAULTS)
        comp = rnd.choice([c for c in comp_pool if f"-{sysname}-" in c])
        turbine = comp.split("-")[0] + "-" + comp.split("-")[1]
        day = rnd.randint(0, DAYS - 1)
        maint_rows.append(
            f"{{id:'ME-{m:04d}', comp:'{comp}', turbine:'{turbine}', "
            f"fault:'{fault}', severity:'{severity}', "
            f"reported_at:'{_ts(day * 24)}', action:'{rnd.choice(ACTIONS)}'}}"
        )
    _emit_batches(
        w,
        maint_rows,
        200,
        "UNWIND $rows AS r "
        "MATCH (c:Component {id:r.comp}), (t:Turbine {id:r.turbine}) "
        "CREATE (c)-[:HAS_EVENT]->(m:MaintenanceEvent "
        "{id:r.id, fault:r.fault, severity:r.severity, "
        "reported_at:datetime(r.reported_at), corrective_action:r.action}) "
        "CREATE (m)-[:AFFECTS]->(t)",
    )

    out = Path(__file__).with_name("seed.cypher")
    out.write_text("\n".join(lines) + "\n")
    n_readings = rc
    print(
        f"Wrote {out} — {FLEET_SIZE} turbines, {len(sensor_ids)} sensors, "
        f"{n_readings} readings, {MAINT_EVENTS} maintenance events."
    )


def _sensor_on_system(stype: str, sysname: str) -> bool:
    mapping = {
        "GearboxTemp": "Drivetrain",
        "Vibration": "Drivetrain",
        "RotorRPM": "Rotor",
        "PowerOutput": "Generator",
        "WindSpeed": "Rotor",
    }
    return mapping[stype] == sysname


def _ts(hour_offset: int) -> str:
    # naive hour arithmetic on the fixed START date; good enough for a demo.
    from datetime import datetime, timedelta

    base = datetime.fromisoformat(START)
    return (base + timedelta(hours=hour_offset)).isoformat()


def _emit_batches(w, rows: list[str], size: int, cypher: str) -> None:
    # Inline each batch's rows directly into the statement as a Cypher list
    # literal (replacing the $rows placeholder), so the whole seed is plain
    # Cypher runnable with `cypher-shell -f seed.cypher` — no client params.
    for i in range(0, len(rows), size):
        chunk = ",\n".join(rows[i : i + size])
        w(cypher.replace("$rows", f"[{chunk}]") + ";")


if __name__ == "__main__":
    main()
