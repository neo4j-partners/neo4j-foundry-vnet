$ErrorActionPreference = 'Stop'
Set-Location (Join-Path $PSScriptRoot '..')

function Get-AzdValue([string]$Name) {
  $value = azd env get-value $Name 2>$null
  if ($LASTEXITCODE -eq 0 -and $value -notlike 'ERROR:*') { return $value }
  return ''
}

$resourceGroup = Get-AzdValue 'foundryResourceGroup'
$keyVaultName = Get-AzdValue 'keyVaultName'
if ($resourceGroup -and $keyVaultName) {
  az keyvault update `
    --resource-group $resourceGroup `
    --name $keyVaultName `
    --public-network-access Disabled `
    --default-action Deny `
    --bypass AzureServices `
    --output none
  if ($LASTEXITCODE -ne 0) { throw 'Failed to disable Key Vault public network access.' }
  Write-Host 'Disabled Key Vault public network access after ARM secret seeding.'
}

$lines = @(
  '# Generated by the azd postprovision hook. No database passwords are written here.'
  "AZURE_SUBSCRIPTION_ID=$(Get-AzdValue 'AZURE_SUBSCRIPTION_ID')"
  "AZURE_TENANT_ID=$(Get-AzdValue 'AZURE_TENANT_ID')"
  "FOUNDRY_RESOURCE_GROUP=$(Get-AzdValue 'foundryResourceGroup')"
  "FOUNDRY_ACCOUNT_NAME=$(Get-AzdValue 'foundryAccountName')"
  "FOUNDRY_PROJECT_ID=$(Get-AzdValue 'foundryProjectId')"
  "FOUNDRY_PROJECT_NAME=$(Get-AzdValue 'foundryProjectName')"
  "FOUNDRY_PROJECT_ENDPOINT=$(Get-AzdValue 'foundryProjectEndpoint')"
  "FOUNDRY_MODEL_DEPLOYMENT_NAME=$(Get-AzdValue 'foundryModelDeploymentName')"
  "FOUNDRY_PUBLIC_NETWORK_ACCESS=$(Get-AzdValue 'foundryPublicNetworkAccessOut')"
  "NEO4J_MCP_ENDPOINT=$(Get-AzdValue 'mcpEndpoint')"
  "NEO4J_MCP_CONNECTION_NAME=$(Get-AzdValue 'mcpConnectionName')"
  "MCP_FQDN=$(Get-AzdValue 'mcpFqdn')"
)
Set-Content -Path '.env.deployed' -Value $lines
Write-Host 'Deployment outputs written to .env.deployed (no secrets).'
