#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."

azd_get() {
  local value
  if value="$(azd env get-value "$1" 2>/dev/null)" && [[ "$value" != ERROR:* ]]; then
    printf '%s' "$value"
  fi
}

resource_group="$(azd_get foundryResourceGroup)"
key_vault_name="$(azd_get keyVaultName)"

if [ -n "$resource_group" ] && [ -n "$key_vault_name" ]; then
  az keyvault update \
    --resource-group "$resource_group" \
    --name "$key_vault_name" \
    --public-network-access Disabled \
    --default-action Deny \
    --bypass AzureServices \
    --output none
  echo "Disabled Key Vault public network access after ARM secret seeding."
fi

cat > .env.deployed <<EOF
# Generated by the azd postprovision hook. No database passwords are written here.
AZURE_SUBSCRIPTION_ID=$(azd_get AZURE_SUBSCRIPTION_ID)
AZURE_TENANT_ID=$(azd_get AZURE_TENANT_ID)
FOUNDRY_RESOURCE_GROUP=$(azd_get foundryResourceGroup)
FOUNDRY_ACCOUNT_NAME=$(azd_get foundryAccountName)
FOUNDRY_PROJECT_ID=$(azd_get foundryProjectId)
FOUNDRY_PROJECT_NAME=$(azd_get foundryProjectName)
FOUNDRY_PROJECT_ENDPOINT=$(azd_get foundryProjectEndpoint)
FOUNDRY_MODEL_DEPLOYMENT_NAME=$(azd_get foundryModelDeploymentName)
FOUNDRY_PUBLIC_NETWORK_ACCESS=$(azd_get foundryPublicNetworkAccessOut)
NEO4J_MCP_ENDPOINT=$(azd_get mcpEndpoint)
NEO4J_MCP_CONNECTION_NAME=$(azd_get mcpConnectionName)
MCP_FQDN=$(azd_get mcpFqdn)
EOF

echo "Deployment outputs written to .env.deployed (no secrets)."
